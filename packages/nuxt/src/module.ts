import { existsSync } from 'node:fs'
import { isAbsolute, join, relative, resolve } from 'node:path'
import { CONFIG_FILE_NAMES, DEFAULT_API_PATH, importConfig } from '@easy-cms/core'
import {
  addServerHandler,
  addServerImports,
  addServerPlugin,
  addTypeTemplate,
  createResolver,
  defineNuxtModule,
  useLogger,
} from '@nuxt/kit'
import type { NuxtModule } from '@nuxt/schema'

export interface ModuleOptions {
  /** Path to the Easy CMS config, relative to the project root. Default: `easy-cms.config.ts` (or .mts/.js/.mjs). */
  configPath?: string
  /** Where the REST API is served. Default `/api/cms`. */
  apiPath?: string
  /** Use `X-Forwarded-For` for the client IP (login rate limiting). Only enable behind a proxy you control. */
  trustProxy?: boolean
}

/** Nitro options this module touches. Nitro's own type augmentation is not loaded here. */
interface NitroOptions {
  virtual?: Record<string, string | (() => string)>
  externals?: { inline?: string[]; traceInclude?: string[] }
}

const SERVER = '#easy-cms-local-api'
const HANDLER = '#easy-cms-rest-handler'

const module: NuxtModule<ModuleOptions> = defineNuxtModule<ModuleOptions>({
  meta: {
    name: '@easy-cms/nuxt',
    configKey: 'easyCms',
    compatibility: { nuxt: '>=4.0.0' },
  },
  defaults: {
    apiPath: DEFAULT_API_PATH,
    trustProxy: false,
  },
  async setup(options, nuxt) {
    const logger = useLogger('easy-cms')
    const { resolve: resolveRuntime } = createResolver(import.meta.url)
    const rootDir = nuxt.options.rootDir

    const configPath = options.configPath
      ? isAbsolute(options.configPath)
        ? options.configPath
        : resolve(rootDir, options.configPath)
      : CONFIG_FILE_NAMES.map((name) => join(rootDir, name)).find((path) => existsSync(path))
    if (!configPath || !existsSync(configPath)) {
      logger.warn(
        `No Easy CMS config found in ${rootDir}. Create easy-cms.config.ts (or run \`npx create-easy-cms\`). The module is disabled.`,
      )
      return
    }

    const apiPath = `/${(options.apiPath ?? DEFAULT_API_PATH).replace(/^\/+|\/+$/g, '')}`
    // Forward slashes: Rollup accepts them on Windows too, and backslashes would need escaping.
    const slash = (path: string) => path.replace(/\\/g, '/')
    const runtime = (file: string) => JSON.stringify(slash(resolveRuntime(`./runtime/${file}`)))
    const config = JSON.stringify(slash(configPath))
    const nitro = (nuxt.options as unknown as { nitro: NitroOptions }).nitro

    // Virtual modules are always bundled by Nitro, so the user's TypeScript config is compiled
    // with the server in both dev and production.
    nitro.virtual = {
      ...nitro.virtual,
      [SERVER]: `import config from ${config}
import { getEasyCMS, getEasyCMSUser } from ${runtime('cms.js')}
export function useEasyCMS() { return getEasyCMS(config) }
export function useEasyCMSUser(event) { return getEasyCMSUser(config, event) }
`,
      [HANDLER]: `import config from ${config}
import { createHandler } from ${runtime('handler.js')}
export default createHandler(config, ${JSON.stringify({ basePath: apiPath, trustProxy: options.trustProxy ?? false })})
`,
    }

    // Types for the virtual module; the config is imported as a type so its literal
    // collection types flow into useEasyCMS().
    addTypeTemplate(
      {
        filename: 'types/easy-cms.d.ts',
        getContents: ({ nuxt: n }) => {
          const from = relative(join(n.options.buildDir, 'types'), configPath)
            .replace(/\\/g, '/')
            .replace(/\.(m?ts|m?js)$/, '')
          // No top-level import/export: this must stay a script so the block declares the module.
          return `// Generated by @easy-cms/nuxt
declare module '${SERVER}' {
  import type { AuthUser, EasyCMS } from '@easy-cms/core'
  import type { H3Event } from 'h3'
  type Config = typeof import('${from.startsWith('.') ? from : `./${from}`}').default

  /** The Easy CMS Local API for this server. */
  export function useEasyCMS(): Promise<EasyCMS<Config>>
  /** The logged-in Easy CMS user for this request (session cookie or Bearer token), or null. */
  export function useEasyCMSUser(event: H3Event): Promise<AuthUser | null>
}
`
        },
      },
      { nitro: true, nuxt: false },
    )

    addServerImports([
      { name: 'useEasyCMS', from: SERVER },
      { name: 'useEasyCMSUser', from: SERVER },
    ])
    addServerHandler({ route: apiPath, handler: HANDLER })
    addServerHandler({ route: `${apiPath}/**`, handler: HANDLER })
    addServerPlugin(resolveRuntime('./runtime/plugin.js'))

    // The runtime imports the virtual modules, so Nitro must bundle it rather than load it from node_modules.
    const runtimeDir = resolveRuntime('./runtime')
    nitro.externals = {
      ...nitro.externals,
      inline: [...(nitro.externals?.inline ?? []), runtimeDir],
    }

    // Ship files the database adapter loads dynamically (e.g. libsql's native binary),
    // which Nitro's output tracing cannot find on its own.
    let traceInclude: readonly string[] = []
    try {
      traceInclude = (await importConfig(configPath))?.db?.bundle?.traceInclude ?? []
    } catch (error) {
      logger.warn(`Could not read ${configPath} at build time: ${(error as Error).message}`)
    }
    if (traceInclude.length > 0) {
      const externals = nitro.externals ?? {}
      nitro.externals = {
        ...externals,
        traceInclude: [...(externals.traceInclude ?? []), ...traceInclude],
      }
    }

    // The database file changes at runtime; don't restart the dev server for it.
    nuxt.options.ignore.push('**/*.db', '**/*.db-*', 'easy-cms/migrations/**')
    nuxt.options.watch.push(configPath)

    logger.info(`Easy CMS API at ${apiPath}`)
  },
})

export default module
